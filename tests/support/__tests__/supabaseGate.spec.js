import { describe, expect, it } from 'vitest'
import { forAll, int, pick } from '../../../src/__tests__/helpers/gen.js'
import {
  ALL_VARS,
  DEFAULT_TIMEOUT_MS,
  PREFLIGHT_PATH,
  SEED_MISSING_REASON,
  VARS,
  gateFor,
  preflight,
  presence,
  resolveGate,
} from '../supabaseGate.js'

// The Gate: the Supabase gate is enabled only when every variable its tier needs is
// set, SKIP_SUPABASE is not '1' and the preflight returned 2xx. Otherwise it reports a skip
// reason built only from fixed text, variable names, an HTTP status or an error name.
// All env values below are synthetic, not taken from real env.

const SYNTHETIC = {
  VITE_SUPABASE_URL: 'https://synthref0000.supabase.co',
  VITE_SUPABASE_ANON_KEY: 'sb_publishable_synthetic-anon-key',
  E2E_SUPABASE_EMAIL: 'guest.synthetic@example.test',
  E2E_SUPABASE_PASSWORD: 'Synth#Pass-0001',
  E2E_SUPABASE_HOST_EMAIL: 'host.synthetic@example.test',
  E2E_SUPABASE_HOST_PASSWORD: 'Synth#Pass-0002',
}
const SECRET_VARS = [...VARS.base, ...VARS.account, ...VARS.host]
const NEEDS = ['account', 'host', 'writes', 'seed']
const PREFLIGHT_KINDS = ['ok', 'ok', 'ok', 'http', 'TypeError', 'AbortError', 'TimeoutError']

const REASON_TEMPLATES = [
  /^Supabase-gated: SKIP_SUPABASE=1$/,
  new RegExp(`^Supabase-gated: (${ALL_VARS.join('|')}) not set$`),
  /^Supabase-gated: preflight HTTP \d{3}$/,
  /^Supabase-gated: preflight failed \([A-Za-z]+\)$/,
  /^Supabase-gated: preflight timed out after \d+ ms$/,
  /^Supabase-gated: E2E_SUPABASE_WRITES is not 1$/,
]
const fromTemplate = (reason) =>
  reason === SEED_MISSING_REASON || REASON_TEMPLATES.some((re) => re.test(reason))

/** Random gate input: presence map, switches, tier needs and a preflight outcome. */
function genCase(r) {
  const env = {}
  for (const name of SECRET_VARS) {
    // Mostly set, so the later checks in the order are reached often.
    if (r() < 0.8) env[name] = name === 'VITE_SUPABASE_URL' ? pick(r, [SYNTHETIC[name], `${SYNTHETIC[name]}/`]) : SYNTHETIC[name]
    else if (r() < 0.5) env[name] = ''
  }
  const writes = pick(r, ['1', '1', '0', '', 'true', undefined])
  if (writes !== undefined) env[VARS.writes] = writes
  const skip = pick(r, ['', '0', 'true', undefined, undefined, '1'])
  if (skip !== undefined) env[VARS.skip] = skip

  const needs = NEEDS.filter(() => r() < 0.4)
  const kind = pick(r, PREFLIGHT_KINDS)
  const status = kind === 'ok' ? int(r, 200, 299) : kind === 'http' ? int(r, 300, 599) : undefined
  return { env, needs, kind, status, seed: r() < 0.7 }
}

/** The result `preflight()` would return for an outcome, plus the caller's seed flag. */
function preflightResultOf({ kind, status, seed }, timeoutMs = DEFAULT_TIMEOUT_MS) {
  if (kind === 'ok') return { ok: true, status, seed }
  if (kind === 'http') return { ok: false, status }
  if (kind === 'TimeoutError') return { ok: false, errorName: kind, timedOut: true, timeoutMs }
  return { ok: false, errorName: kind }
}

/** Independent statement of the documented check order; returns the first failing reason. */
function expectedReason({ env, needs, kind, status, seed }) {
  const want = new Set(needs)
  const needAccount = ['account', 'host', 'writes', 'seed'].some((n) => want.has(n))
  const needWrites = want.has('writes') || want.has('seed')
  const missing = (names) => names.find((name) => !env[name])

  if (env.SKIP_SUPABASE === '1') return 'Supabase-gated: SKIP_SUPABASE=1'
  if (missing(VARS.base)) return `Supabase-gated: ${missing(VARS.base)} not set`
  if (kind === 'http') return `Supabase-gated: preflight HTTP ${status}`
  if (kind === 'TimeoutError') return `Supabase-gated: preflight timed out after ${DEFAULT_TIMEOUT_MS} ms`
  if (kind !== 'ok') return `Supabase-gated: preflight failed (${kind})`
  if (needAccount && missing(VARS.account)) return `Supabase-gated: ${missing(VARS.account)} not set`
  if (want.has('host') && missing(VARS.host)) return `Supabase-gated: ${missing(VARS.host)} not set`
  if (needWrites && env.E2E_SUPABASE_WRITES !== '1') return 'Supabase-gated: E2E_SUPABASE_WRITES is not 1'
  if (want.has('seed') && seed !== true) return SEED_MISSING_REASON
  return null
}

/** Run an async check over cases generated by `forAll`, annotating a failure like `forAll`. */
async function forEachCase(gen, fn, { n, seed }) {
  const cases = []
  forAll(gen, (c) => { cases.push(c) }, { n, seed })
  for (const [i, c] of cases.entries()) {
    try {
      await fn(c)
    } catch (e) {
      e.message = `[seed ${seed}, case ${i}] ${JSON.stringify(c)}\n${e.message}`
      throw e
    }
  }
}

/** Injected fetch that records every call and answers with the case's outcome. */
function countingFetch({ kind, status }) {
  const calls = []
  const fetchImpl = async (url, init) => {
    calls.push({ url, init })
    if (kind === 'ok' || kind === 'http') return { ok: status >= 200 && status < 300, status, body: null }
    if (kind === 'TypeError') throw new TypeError('fetch failed')
    throw Object.assign(new Error('synthetic failure'), { name: kind })
  }
  return { calls, fetchImpl }
}

describe('Supabase gate (Property 4)', () => {
  it('enables a tier exactly when the conjunction holds and otherwise names the first failing check', () => {
    forAll(genCase, (c) => {
      const result = gateFor(c.env, preflightResultOf(c), c.needs)
      const expected = expectedReason(c)

      expect(result.enabled).toBe(expected === null)
      expect(result.reason === null).toBe(result.enabled)
      expect(result.reason).toBe(expected)
      if (result.reason !== null) expect(fromTemplate(result.reason), result.reason).toBe(true)
    }, { n: 500, seed: 4216 })
  })

  it('sends no request for SKIP_SUPABASE=1 or a missing base variable, and exactly one read-only GET otherwise', async () => {
    await forEachCase(genCase, async (c) => {
      const { calls, fetchImpl } = countingFetch(c)
      const result = await resolveGate(c.env, { needs: c.needs, fetchImpl })
      const early = c.env.SKIP_SUPABASE === '1' || VARS.base.some((name) => !c.env[name])

      // resolveGate never confirms the demo seed, so seed-needing tiers stay disabled.
      expect(result.reason).toBe(expectedReason({ ...c, seed: false }))
      expect(result.enabled).toBe(result.reason === null)

      if (early) {
        expect(calls).toHaveLength(0)
        return
      }
      expect(calls).toHaveLength(1)
      const [{ url, init }] = calls
      const target = new URL(url)
      expect(`${target.origin}${target.pathname}`).toBe(`${c.env.VITE_SUPABASE_URL.replace(/\/+$/, '')}/rest/v1/places`)
      expect(url.endsWith(PREFLIGHT_PATH)).toBe(true)
      expect(target.searchParams.get('select')).toBe('id')
      expect(target.searchParams.get('limit')).toBe('1')
      expect(init.method).toBe('GET')
      expect(init.body).toBeUndefined()
      expect(init.headers).toEqual({ apikey: c.env.VITE_SUPABASE_ANON_KEY })
      expect(typeof init.signal?.aborted).toBe('boolean')
    }, { n: 300, seed: 4217 })
  })

  it('reports a timed-out preflight by its timeout, never throwing', async () => {
    const env = { VITE_SUPABASE_URL: SYNTHETIC.VITE_SUPABASE_URL, VITE_SUPABASE_ANON_KEY: SYNTHETIC.VITE_SUPABASE_ANON_KEY }
    const hang = (_url, init) => new Promise((_resolve, reject) => {
      init.signal.addEventListener('abort', () => reject(init.signal.reason))
    })

    const result = await preflight(env, { fetchImpl: hang, timeoutMs: 20 })

    expect(result).toEqual({ ok: false, errorName: 'TimeoutError', timedOut: true, timeoutMs: 20 })
    expect(gateFor(env, result)).toEqual({ enabled: false, reason: 'Supabase-gated: preflight timed out after 20 ms' })
  })

  it('reports presence as names and booleans only', () => {
    forAll(genCase, ({ env }) => {
      const report = presence(env)
      expect(report.map(({ name }) => name)).toEqual([...ALL_VARS])
      for (const entry of report) {
        expect(Object.keys(entry).sort()).toEqual(['name', 'set'])
        expect(entry.set).toBe(Boolean(env[entry.name]))
      }
    }, { n: 100, seed: 4218 })
  })
})
