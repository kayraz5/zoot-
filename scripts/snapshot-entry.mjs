// pnpm snapshot:entry -> saves today's ICA visa list, Passport Index rules for Singapore and 3-letter country codes into
// src/model/data/sgEntrySnapshot.js, the fallback the app and /api/entry-rule use when the live sources fail.
import { writeFileSync } from 'node:fs'
import { fetchIcaSlugs, fetchIndexRules, fetchIso3Codes } from '../api/_lib/immigration.js'
import previous from '../src/model/data/sgEntrySnapshot.js'

const OUT_FILE = new URL('../src/model/data/sgEntrySnapshot.js', import.meta.url)
const today = new Date().toISOString().slice(0, 10)

const [slugs, rules, iso3] = await Promise.all([fetchIcaSlugs(), fetchIndexRules(), fetchIso3Codes()])

const added = slugs.filter((s) => !previous.ica.slugs.includes(s))
const removed = previous.ica.slugs.filter((s) => !slugs.includes(s))
if (added.length || removed.length) console.log(`[snapshot-entry] ICA list changed: +${added.join(', ') || '-'} / -${removed.join(', ') || '-'} (recheck VFTF in immigration.js)`)

const snapshot = { generatedOn: today, ica: { checkedOn: today, slugs }, index: { checkedOn: today, rules }, iso3 }
writeFileSync(OUT_FILE, `// Generated by \`pnpm snapshot:entry\`. Fallback for /api/entry-rule when ICA or the Passport Index can't be reached.\nexport default ${JSON.stringify(snapshot, null, 2)}\n`)
console.log(`[snapshot-entry] saved ${slugs.length} ICA visa countries and ${Object.keys(rules).length} passports`)
